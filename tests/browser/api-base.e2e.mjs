// Real settings, model tests and activation routes against a local HTTP double.
import { test, expect } from "@playwright/test";
import { ensureOwnerSession } from "./session.mjs";

test("提供方统一保存，OpenAI已有授权与iliad模型往返保留，未通过测试不可启用", async ({ page }, info) => {
  await ensureOwnerSession(page.request);
  await page.request.post("/api/ai/login", { data: { providerId: "openai" } });
  await page.request.get("/auth/callback?state=ui-test-state&code=ui-test-code");
  const originalOpenAI = await (await page.request.get("/api/ai/status")).json();
  expect(originalOpenAI.connected).toBe(true);
  let authorizations = 0;
  page.on("request", (request) => {
    const url = new URL(request.url());
    if (url.pathname === "/api/ai/login" || url.hostname === "auth.openai.com") authorizations++;
  });
  const open = async () => {
    await expect(page.locator(".main-panel")).toBeVisible();
    const drawer = page.getByRole("button", { name: "打开书架", exact: true });
    if (await drawer.isVisible()) await drawer.click();
    await page.getByRole("button", { name: "AI 设置", exact: true }).click();
  };
  await page.goto("/");
  await open();
  const providers = page.getByRole("combobox", { name: "AI 提供方", exact: true });
  const keyValue = `fixture-only-ui-key-${info.project.name}`;
  const state = async (providerId) => (await (await page.request.get(`/api/ai/status${providerId ? `?providerId=${providerId}` : ""}`)).json());
  try {
    await providers.selectOption("api_base");
    await expect(providers.locator('option[value="api_base"]')).toHaveText("iliad codix");
    const form = page.getByRole("form", { name: "iliad codix 配置" });
    const models = page.getByRole("combobox", { name: "待测试模型", exact: true });
    const save = page.getByRole("button", { name: "保存 API 配置", exact: true });
    const use = page.getByRole("button", { name: "保存提供方", exact: true });
    await expect(use).toHaveCount(1);
    await expect(page.getByRole("button", { name: "使用此模型", exact: true })).toHaveCount(0);
    expect((await state()).providerId).toBe("openai");
    const key = page.getByLabel("API key", { exact: true });
    const testSelected = () => page.getByRole("button", { name: /^(测试所选模型|重新测试模型)$/ });
    await expect(form).toContainText("尚未配置 API key");
    await expect(use).toBeDisabled();
    await expect(testSelected()).toBeDisabled();
    await expect(key).toHaveAttribute("type", "password");
    await expect(form.locator('input[type="url"]')).toHaveCount(0);
    await expect(form).toContainText("服务地址：https://iliad.codix.scw.eu/v1");
    await key.fill(keyValue);
    await models.selectOption("codiX-agent");
    await expect(save).toBeEnabled();
    await save.click();
    await expect(form).toContainText("已保存 API key");
    await expect(key).toHaveValue("");
    await expect(page.getByLabel("当前使用模型", { exact: true })).toContainText("尚未启用模型");
    expect((await state("api_base")).connected).toBe(false);
    expect((await state()).providerId).toBe("openai");
    await expect(page.getByLabel("模型列表来源", { exact: true })).toContainText("服务端返回 3 个可选模型");
    await expect(models.locator("option")).toHaveCount(4);
    await expect(page.getByLabel("模型列表来源", { exact: true })).toContainText("已排除 3 个");
    await expect(use).toBeDisabled();
    const bypass = await page.request.post("/api/providers/active", { data: { providerId: "api_base", model: "codiX-agent" } });
    expect(bypass.status()).toBe(409);
    await testSelected().click();
    const results = page.getByLabel("所选模型测试结果", { exact: true });
    await expect(results).toContainText("图片输入：不支持");
    await expect(use).toBeDisabled();
    await expect(save).toBeEnabled();
    await models.selectOption("Qwen/Qwen3.6-35B");
    await expect(use).toBeDisabled();
    await testSelected().click();
    await expect(results).toContainText("图片输入：通过");
    await expect(results).toContainText("JSON 输出：通过");
    await expect(results).toContainText("流式文本：通过");
    await expect(use).toBeEnabled();
    expect((await state("api_base")).connected).toBe(false);
    expect((await state()).providerId).toBe("openai");
    await use.click();
    await expect(page.getByLabel("当前使用模型", { exact: true })).toContainText("Qwen/Qwen3.6-35B");
    expect((await state()).connected).toBe(true);
    expect((await state()).providerId).toBe("api_base");
    await models.selectOption("Zai/GLM-5.2");
    await expect(use).toBeDisabled();
    await page.getByRole("button", { name: "刷新模型列表", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("获取 3 个可选模型");
    await expect(models).toHaveValue("Zai/GLM-5.2");
    expect((await state()).configuration.activeModel).toBe("Qwen/Qwen3.6-35B");
    await models.selectOption("Qwen/Qwen3.6-35B");
    await expect(results).toContainText("测试通过");
    await providers.selectOption("openai");
    await expect(page.getByText("已授权", { exact: true })).toBeVisible();
    await expect(use).toHaveCount(1);
    await expect(use).toBeEnabled();
    expect((await state()).providerId).toBe("api_base");
    await use.click();
    await expect(page.getByRole("status")).toContainText("继续使用已保存的 ChatGPT 授权");
    expect((await state()).activeAccountId).toBe(originalOpenAI.activeAccountId);
    expect((await state()).providerId).toBe("openai");
    expect((await state()).connected).toBe(true);
    await expect(page.getByRole("button", { name: "Continue with ChatGPT", exact: true })).toHaveCount(0);
    await providers.selectOption("api_base");
    await expect(form).toContainText("已保存 API key");
    await expect(results).toContainText("测试通过");
    await expect(use).toBeEnabled();
    expect((await state()).providerId).toBe("openai");
    await use.click();
    await expect(page.getByRole("status")).toContainText("已保存提供方：iliad codix");
    expect((await state()).configuration.activeModel).toBe("Qwen/Qwen3.6-35B");
    expect(authorizations).toBe(0);
    await page.screenshot({ path: `artifacts/api-base-settings-${info.project.name}.png`, fullPage: true });
    expect(JSON.stringify(await state())).not.toContain(keyValue);
    await page.reload();
    await open();
    await expect(page.getByLabel("当前使用模型", { exact: true })).toContainText("Qwen/Qwen3.6-35B");
    await expect(results).toContainText("测试通过");
    await expect(key).toHaveValue("");
    await key.fill(`${keyValue}-replacement`);
    await expect(use).toBeDisabled();
    await expect(testSelected()).toBeDisabled();
    await expect(save).toBeEnabled();
    await save.click();
    await expect(page.getByRole("status")).toContainText("API 配置已保存");
    await expect(page.getByLabel("当前使用模型", { exact: true })).toContainText("尚未启用模型");
    await expect(use).toBeDisabled();
    expect((await state()).connected).toBe(false);
    await page.getByRole("button", { name: "移除 API key", exact: true }).click();
    await expect(form).toContainText("尚未配置 API key");
    await providers.selectOption("openai");
    await expect(use).toBeEnabled();
    await use.click();
    await expect(page.getByText("已授权", { exact: true })).toBeVisible();
    expect((await state()).providerId).toBe("openai");
    expect((await state()).activeAccountId).toBe(originalOpenAI.activeAccountId);
    expect(authorizations).toBe(0);
  } finally {
    await page.request.post("/api/ai/logout", { data: { providerId: "api_base" } });
    await page.request.post("/api/providers/active", { data: { providerId: "openai" } });
  }
});
